<?php
declare(strict_types=1);

require_once __DIR__ . '/auth.php';
require_roles(['super_admin']);
require_once __DIR__ . '/config/database.php';

try {
    $pdo = database_connection();
    $databaseName = (string) $pdo->query('SELECT DATABASE()')->fetchColumn();
    if ($databaseName === '') {
        throw new RuntimeException('No database selected.');
    }

    $tablesStmt = $pdo->prepare(
        "SELECT TABLE_NAME FROM information_schema.TABLES
         WHERE TABLE_SCHEMA = :database_name AND TABLE_TYPE = 'BASE TABLE'
         ORDER BY TABLE_NAME"
    );
    $tablesStmt->execute(['database_name' => $databaseName]);
    $tables = $tablesStmt->fetchAll(PDO::FETCH_COLUMN);

    $filename = 'student_id_generator_backup_' . date('Y-m-d_H-i-s') . '.sql';
    header('Content-Type: application/sql; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: no-store, no-cache, must-revalidate');
    header('Pragma: no-cache');

    echo "-- Database backup generated by Student Management System\n";
    echo "-- Database: " . str_replace(["\r", "\n"], '', $databaseName) . "\n";
    echo "-- Generated: " . date(DATE_ATOM) . "\n";
    echo "-- Includes table definitions and table data. Review before restoring.\n\n";
    echo "SET NAMES utf8mb4;\n";
    echo "SET FOREIGN_KEY_CHECKS=0;\n";
    echo "SET SQL_MODE='NO_AUTO_VALUE_ON_ZERO';\n\n";

    $tick = chr(96);
    foreach ($tables as $table) {
        $safeTable = str_replace($tick, $tick . $tick, (string) $table);
        $createStmt = $pdo->query('SHOW CREATE TABLE ' . $tick . $safeTable . $tick);
        $createRow = $createStmt->fetch(PDO::FETCH_NUM);
        if (!$createRow || !isset($createRow[1])) {
            continue;
        }

        echo "-- --------------------------------------------------------\n";
        echo "-- Table: " . $tick . $safeTable . $tick . "\n";
        echo "DROP TABLE IF EXISTS " . $tick . $safeTable . $tick . ";\n";
        echo $createRow[1] . ";\n\n";

        $dataStmt = $pdo->query('SELECT * FROM ' . $tick . $safeTable . $tick, PDO::FETCH_ASSOC);
        $columnMeta = $pdo->query('SHOW COLUMNS FROM ' . $tick . $safeTable . $tick)->fetchAll(PDO::FETCH_ASSOC);
        $columnNames = [];
        foreach ($columnMeta as $column) {
            $columnNames[] = $tick . str_replace($tick, $tick . $tick, (string) $column['Field']) . $tick;
        }
        $columnList = implode(', ', $columnNames);

        $batchSize = 100;
        $batch = [];
        while ($row = $dataStmt->fetch(PDO::FETCH_ASSOC)) {
            $values = [];
            foreach ($row as $value) {
                if ($value === null) {
                    $values[] = 'NULL';
                } elseif (is_int($value) || is_float($value)) {
                    $values[] = (string) $value;
                } else {
                    $quoted = $pdo->quote((string) $value);
                    $values[] = $quoted === false ? "''" : $quoted;
                }
            }
            $batch[] = '(' . implode(', ', $values) . ')';
            if (count($batch) >= $batchSize) {
                echo 'INSERT INTO ' . $tick . $safeTable . $tick . ' (' . $columnList . ") VALUES\n";
                echo implode(",\n", $batch) . ";\n";
                $batch = [];
            }
        }
        if ($batch !== []) {
            echo 'INSERT INTO ' . $tick . $safeTable . $tick . ' (' . $columnList . ") VALUES\n";
            echo implode(",\n", $batch) . ";\n";
        }
        echo "\n";
    }

    echo "SET FOREIGN_KEY_CHECKS=1;\n";
} catch (Throwable $exception) {
    error_log('Database backup export failed: ' . $exception->getMessage());
    if (!headers_sent()) {
        http_response_code(500);
        header('Content-Type: text/plain; charset=UTF-8');
    }
    echo "Database backup failed. Check the PHP/Apache error log and database connection.\n";
}
